def write_outputs() -> None:
    public_labs = []
    teacher_data = {}
    for lab in LABS:
        public = {key: value for key, value in lab.items() if key not in {"teacher"}}
        public_labs.append(public)
        teacher_data[lab["id"]] = lab["teacher"]

        teacher_path = ROOT / lab["teacherGuide"]
        teacher_path.parent.mkdir(parents=True, exist_ok=True)
        teacher_path.write_text(teacher_card(lab), encoding="utf-8")

        student_dir = ROOT / f"course-{lab['course']}" / f"semester-{lab['semester']}"
        student_dir.mkdir(parents=True, exist_ok=True)
        (student_dir / f"{lab['id']}.md").write_text(student_card(lab), encoding="utf-8")

    content_dir = ROOT / "content"
    content_dir.mkdir(parents=True, exist_ok=True)
    labs_payload = json.dumps(public_labs, ensure_ascii=False, indent=2) + "\n"
    teacher_payload = json.dumps(teacher_data, ensure_ascii=False, indent=2) + "\n"
    combined = (labs_payload + teacher_payload).lower()
    forbidden_legacy_name = "mood" + "le"
    if forbidden_legacy_name in combined:
        raise RuntimeError("Запрещённое название платформы найдено в генерируемом контенте")
    (content_dir / "labs.json").write_text(labs_payload, encoding="utf-8")
    (content_dir / "teacher-guides.json").write_text(teacher_payload, encoding="utf-8")
    docs_dir = ROOT / "docs"
    docs_dir.mkdir(parents=True, exist_ok=True)
    (docs_dir / "COVERAGE_MATRIX.md").write_text(coverage_matrix(), encoding="utf-8")
    print(f"Generated {len(LABS)} labs")


if __name__ == "__main__":
    write_outputs()
